// Publish only Vite's output into the existing Ars/ directory in this Pages repo.
import { copyFile, mkdir, readFile, readdir, unlink, writeFile } from "node:fs/promises";
import { fileURLToPath } from "node:url";
import { join } from "node:path";

const root = fileURLToPath(new URL("../", import.meta.url));
const dist = join(root, "dist");
const manifest = join(root, "pages-assets.json");

let previous = [];
try {
  previous = JSON.parse(await readFile(manifest, "utf8"));
} catch (error) {
  if (error.code !== "ENOENT") throw error;
}
if (!Array.isArray(previous) || previous.some(path => typeof path !== "string" || !/^assets\/[A-Za-z0-9_.-]+$/.test(path))) {
  throw new Error("Invalid pages-assets.json; expected generated asset paths only.");
}

const entries = await readdir(join(dist, "assets"), { withFileTypes: true });
if (entries.some(entry => !entry.isFile())) throw new Error("Unexpected nested build assets; update the publisher before proceeding.");
const assets = entries.map(entry => `assets/${entry.name}`).sort();
await mkdir(join(root, "assets"), { recursive: true });
for (const path of assets) await copyFile(join(dist, path), join(root, path));
await copyFile(join(dist, "index.html"), join(root, "index.html"));
// Remove only obsolete files recorded as generated by the previous publication.
for (const path of previous.filter(path => !assets.includes(path))) {
  try { await unlink(join(root, path)); } catch (error) { if (error.code !== "ENOENT") throw error; }
}
await writeFile(manifest, JSON.stringify(assets, null, 2) + "\n");
console.log(`Prepared index.html and ${assets.length} assets for /Ars/. Commit them with the project source.`);
