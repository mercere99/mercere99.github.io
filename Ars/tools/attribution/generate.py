"""Generate ATTRIBUTION.md from the provenance carried by every data record.

Run after any ingest. The output is checked in so that CC BY-SA attribution
stays accurate without anyone maintaining it by hand.
"""

from __future__ import annotations

import json
import sys
from collections import Counter, defaultdict
from pathlib import Path

GENERAL = (
    "Based on the material for Ars Magica, \u00a91993\u20132024, licensed by "
    "Trident, Inc. d/b/a Atlas Games\u00ae, under Creative Commons "
    "Attribution-ShareAlike 4.0 International license 4.0 (\"CC-BY-SA 4.0\")"
)

TRADEMARKS = """Ars Magica Open License Logo \u00a92024 Trident, Inc. The Ars Magica Open \
License Logo, Ars Magica, and Mythic Europe are trademarks of Trident, Inc., \
and are used with permission.

Order of Hermes, Tremere, Doissetep, and Grimgroth are trademarks of Paradox \
Interactive AB and are used with permission."""


def collect(data_dir: Path) -> tuple[Counter, dict[str, Counter]]:
    """Count records per source book, and adaptation kinds per book."""
    per_book: Counter = Counter()
    adaptations: dict[str, Counter] = defaultdict(Counter)
    for path in sorted(data_dir.rglob("*.json")):
        payload = json.loads(path.read_text(encoding="utf-8"))
        for record in payload.get("records", []):
            src = record.get("source")
            if not src:
                continue
            key = f"{src['book']} ({src['year']})"
            per_book[key] += 1
            adaptations[key][record.get("adaptation", "unknown")] += 1
    return per_book, adaptations


def render(per_book: Counter, adaptations: dict[str, Counter]) -> str:
    lines = [
        "# Attribution",
        "",
        "This file is generated by `tools/attribution/generate.py`. Do not edit "
        "it by hand.",
        "",
        "## General attribution",
        "",
        f"> {GENERAL}",
        "",
        "## Trademarks",
        "",
        *(f"> {line}" if line else ">" for line in TRADEMARKS.split("\n")),
        "",
        "## Source books used",
        "",
        "| Book | Records | Adaptation |",
        "| --- | ---: | --- |",
    ]
    for book, count in sorted(per_book.items()):
        kinds = ", ".join(
            f"{kind} {n}" for kind, n in sorted(adaptations[book].items())
        )
        lines.append(f"| {book} | {count} | {kinds} |")
    lines += [
        "",
        "## Changes made",
        "",
        "CC BY-SA 4.0 requires that changes be indicated. Every record carries "
        "an `adaptation` field:",
        "",
        "- `verbatim` — the text is reproduced unchanged, with only markdown "
        "formatting removed.",
        "- `abridged` — non-mechanical prose has been trimmed.",
        "- `restructured` — prose has been converted into structured fields "
        "(tables into records, narrative rules into algorithms).",
        "- `original` — written for this project and not derived from any "
        "published book.",
        "",
        "## Not included",
        "",
        "No trade dress, graphic design, artwork, cartography, or logos from "
        "any Ars Magica publication appear in this repository. These are not "
        "covered by the open license.",
        "",
    ]
    return "\n".join(lines)


def main(root: Path) -> None:
    per_book, adaptations = collect(root / "data")
    (root / "ATTRIBUTION.md").write_text(
        render(per_book, adaptations), encoding="utf-8"
    )
    total = sum(per_book.values())
    print(f"  ATTRIBUTION.md: {total} records across {len(per_book)} book(s)")


if __name__ == "__main__":
    main(Path(sys.argv[1] if len(sys.argv) > 1 else "."))
