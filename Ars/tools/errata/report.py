"""Generate ERRATA.md — a submission-ready report of every correction and
observation, grouped by where it should be filed.

Run:  python3 tools/errata/report.py .
"""

from __future__ import annotations

import json
import sys
from collections import defaultdict
from pathlib import Path

DESTINATION_HEADINGS = {
    "corpus": (
        "For the transcription maintainers",
        "The markdown differs from the printed book. File at "
        "<https://github.com/OriginalMadman/Ars-Magica-Open-License/issues>.",
    ),
    "publisher": (
        "For Atlas Games",
        "The printed book itself is wrong, inconsistent, or ambiguous. These "
        "are candidates for official errata.",
    ),
    "project": (
        "Our own normalization choices",
        "Not errors in the source — decisions this project made, recorded so "
        "they are visible rather than buried in a parser.",
    ),
}

OPEN_STATUSES = {"unreported", "submitted"}


def render(records: list[dict]) -> str:
    by_dest: dict[str, list[dict]] = defaultdict(list)
    for r in records:
        by_dest[r.get("destination", "project")].append(r)

    open_count = sum(1 for r in records if r.get("status") in OPEN_STATUSES)
    lines = [
        "# Errata",
        "",
        "Generated by `tools/errata/report.py`. Do not edit by hand — the source "
        "is `data/errata.json`.",
        "",
        f"{len(records)} item(s) recorded, {open_count} still open.",
        "",
        "Corrections are applied to the extracted data automatically after each "
        "ingest. Observations change nothing here but are worth reporting. Each "
        "item states the value it expects to find, so if the source is fixed "
        "upstream the ingest reports the entry as stale instead of applying it "
        "twice.",
        "",
    ]

    for dest, (heading, blurb) in DESTINATION_HEADINGS.items():
        items = by_dest.get(dest)
        if not items:
            continue
        lines += [f"## {heading}", "", blurb, ""]
        for r in sorted(items, key=lambda x: x["id"]):
            kind = r.get("kind", "correction")
            lines += [
                f"### {r.get('citation', r.get('record', r['id']))}",
                "",
                f"- **id:** `{r['id']}`",
                f"- **kind:** {kind} · **category:** {r.get('category', '—')} "
                f"· **status:** {r.get('status', 'unreported')} "
                f"· **found:** {r.get('found', '—')}",
            ]
            if kind == "correction":
                lines += [
                    f"- **record:** `{r['record']}` field `{r['field']}` "
                    f"in `{r['file']}`",
                    f"- **source reads:** `{json.dumps(r['original'], ensure_ascii=False)}`",
                    f"- **corrected to:** `{json.dumps(r['corrected'], ensure_ascii=False)}`",
                ]
            lines += ["", r.get("note", ""), ""]

    return "\n".join(lines)


def main(root: Path) -> None:
    payload = json.loads((root / "data" / "errata.json").read_text(encoding="utf-8"))
    (root / "ERRATA.md").write_text(render(payload["records"]), encoding="utf-8")
    print(f"  ERRATA.md: {len(payload['records'])} item(s)")


if __name__ == "__main__":
    main(Path(sys.argv[1] if len(sys.argv) > 1 else "."))
